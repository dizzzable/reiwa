/** The point for an ISO 3166-1 alpha-2 code, or `null` when there is none. */
export function countryPoint(code: string | null): CountryPoint | null {
  if (!code) return null;
  // `Object.hasOwn`, not a bare index: a code of `constructor` or `toString`
  // would otherwise return a function from the prototype and be placed as a
  // marker at `NaN`.
  const key = code.trim().toUpperCase();
  return Object.hasOwn(COUNTRY_POINTS, key) ? COUNTRY_POINTS[key] : null;
}
